  assert.equal(await trigger.innerText(), label, "Cancel must not commit the temporary date");
  await trigger.click();
  await page.keyboard.press("Escape");
  await expect(dialog).toBeHidden();
  await expect(trigger).toBeFocused();
  const saved = page.waitForResponse((response) => response.url().includes(`/api/posts/${postId}`) && response.request().method() === "PATCH");
  await page.getByRole("button", { name: "Lagre utkast", exact: true }).click();
  assert((await saved).ok());
  const post = await payload.findByID({ collection: "posts", id: postId, draft: true });
  assert.equal(post.visibility, "private");
  assert.equal(typeof post.photo === "object" ? post.photo?.id : post.photo, mediaId);
  assert(post.publishedAt);
  assert.equal(publicationParts(post.publishedAt).time, "14:30", "Norwegian time is independent of the browser timezone");
  await page.reload();
  await expect(trigger).toContainText("14:30");
  await expect(cover.getByRole("img")).toBeVisible();
  await trigger.click();
  await dialog.getByRole("button", { name: "Sett automatisk", exact: true }).click();
  await expect(trigger).toContainText("Settes ved publisering");
  const published = page.waitForResponse((response) => response.url().includes(`/api/posts/${postId}`) && response.request().method() === "PATCH");
  await page.getByRole("button", { name: "Publiser endringer", exact: true }).click();
  assert((await published).ok());
  const live = await payload.findByID({ collection: "posts", id: postId });
  assert.equal(live._status, "published");
  assert(live.publishedAt && Math.abs(Date.now() - new Date(live.publishedAt).getTime()) < 60_000, "Automatic date is set when publishing");
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole("button", { name: "Lukk meny", exact: true })).toBeHidden();
  await expect(page.getByRole("button", { name: "Legg til skillelinje", exact: true })).toBeVisible();
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), "Mobile page must not overflow");
  await trigger.click();
  await expect(dialog).toBeVisible();
  const box = await dialog.boundingBox();
  assert(box && box.x >= 0 && box.x + box.width <= 390, "Calendar must fit the mobile screen");
  await expect(dialog.getByRole("button", { name: "Bruk dato", exact: true })).toBeInViewport();
