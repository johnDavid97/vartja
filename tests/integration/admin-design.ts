  assert((await context.request.post("/api/users/login", { data: { email, password } })).ok());
  const page = await context.newPage();
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  page.on("console", (message) => { if (message.type() === "error") errors.push(message.text()); });
  await page.goto("/admin/collections/posts/create");
  await expect(page.getByRole("heading", { name: "Nytt innlegg", exact: true })).toBeVisible();
  await expect(page.locator(".app-header .step-nav__home")).toBeHidden();
  await expect(page.locator(".app-header .step-nav__home + span")).toBeHidden();
  await expect(page.locator(".wedding-nav__brand")).toBeVisible();
  await expect(page.getByRole("button", { name: "Program Kommer", exact: true })).toBeDisabled();
  await expect(page.getByRole("button", { name: "Kommentarer Kommer", exact: true })).toBeDisabled();
  await expect(page.getByRole("button", { name: "Avstemninger Kommer", exact: true })).toBeDisabled();
  await expect(page.getByRole("navigation", { name: "Administrasjon" })).toBeVisible();
  const editorBox = await page.locator('.post-visual-editor').boundingBox();
  const publishingBox = await page.locator('.wedding-publishing').boundingBox();
  assert(editorBox && publishingBox && publishingBox.x >= editorBox.x + editorBox.width + 15, "Publishing card must not overlap the editor");
  await page.screenshot({ path: "/tmp/sammen-admin-desktop.png", fullPage: true });
  await page.goto(`/admin/collections/posts/${postId}`);
  await page.getByRole("radio", { name: /^Privat/ }).check();
  const cover = page.getByRole("group", { name: "Forsidebilde", exact: true });
  const chooseInvalid = page.waitForEvent("filechooser");
  await cover.getByRole("button", { name: "Last opp bilde", exact: true }).click();
  await (await chooseInvalid).setFiles({ name: "invalid.txt", mimeType: "text/plain", buffer: Buffer.from("not an image") });
  await expect(cover.getByRole("alert")).toContainText("Velg et JPG");
  const imageData = await sharp({ create: { width: 80, height: 40, channels: 3, background: "#2f5e52" } }).png().toBuffer();
  const uploaded = page.waitForResponse((response) => response.url().endsWith("/api/media") && response.request().method() === "POST");
  const chooseImage = page.waitForEvent("filechooser");
  await cover.getByRole("button", { name: "Last opp bilde", exact: true }).click();
  await (await chooseImage).setFiles({ name: `design-${Date.now()}.png`, mimeType: "image/png", buffer: imageData });
  const uploadResponse = await uploaded;
  assert(uploadResponse.ok());
  mediaId = (await uploadResponse.json()).doc.id;
  await expect(cover.getByRole("img")).toBeVisible();
  await cover.getByRole("button", { name: "Fjern forsidebilde", exact: true }).click();
  await cover.getByRole("button", { name: "Velg fra biblioteket", exact: true }).click();
  const library = page.locator(".list-drawer .admin-table");
  await expect(library).toBeVisible();
  await library.locator(`tr[data-id="${mediaId}"] button`).first().click();
  await expect(library).toBeHidden();
  await expect(cover.getByRole("img")).toBeVisible();
  const trigger = page.getByRole("button", { name: /^Publiseringsdato/ });
  await trigger.click();
  const dialog = page.getByRole("dialog", { name: "Velg publiseringsdato" });
  await expect(dialog).toBeVisible();
  await dialog.getByRole("button", { name: "I dag", exact: true }).click();
  await dialog.getByLabel("Klokkeslett", { exact: true }).fill("14:30");
  await page.screenshot({ path: "/tmp/sammen-admin-date.png", fullPage: true });
  await dialog.getByRole("button", { name: "Bruk dato", exact: true }).click();
  await expect(dialog).toBeHidden();
  await expect(trigger).toContainText("14:30");
